export function translateCondition(condition: string, lang: SupportedLanguage = "en"): string {
  if (!condition || lang === "en") return condition || "Clear Sky";
  const c = condition.toLowerCase();
  const t = TRANSLATIONS[lang] || TRANSLATIONS.en;

  if (c.includes("thunder") || c.includes("lightning") || c.includes("storm")) return t.thunderstorm || condition;
  if (c.includes("drizzle") || c.includes("shower") || c.includes("light rain")) return t.lightDrizzle || condition;
  if (c.includes("rain") || c.includes("precipitation")) return t.rain || condition;
  if (c.includes("snow") || c.includes("ice") || c.includes("sleet") || c.includes("hail")) return t.snow || condition;
  if (c.includes("fog") || c.includes("mist") || c.includes("haze") || c.includes("smoke")) return t.foggy || condition;
  if (c.includes("overcast") || c.includes("cloudy")) return t.overcast || condition;
  if (c.includes("partly") || c.includes("scattered")) return t.partlyCloudy || condition;
  if (c.includes("clear") || c.includes("sun")) return t.clearSky || condition;

  return condition;
}

export function translateAqiCategory(cat: string, lang: SupportedLanguage = "en"): string {
  if (!cat || lang === "en") return cat || "Moderate";
  const c = cat.toLowerCase();
  const t = TRANSLATIONS[lang] || TRANSLATIONS.en;

  if (c.includes("good")) return t.good;
  if (c.includes("satisfactory")) return t.satisfactory;
  if (c.includes("moderate")) return t.moderate;
  if (c.includes("poor") && !c.includes("very")) return t.poor;
  if (c.includes("unhealthy") || c.includes("very poor")) return t.unhealthy;
  if (c.includes("severe") || c.includes("hazardous")) return t.severe;

  return cat;
}

export function translateRole(role: string, lang: SupportedLanguage = "en"): string {
  const r = (role || "").toLowerCase();
  const t = TRANSLATIONS[lang] || TRANSLATIONS.en;

  if (r.includes("farmer")) return t.roleFarmer;
  if (r.includes("pilot") || r.includes("aviator")) return t.rolePilot;
  if (r.includes("disaster") || r.includes("emergency")) return t.roleDisaster;
  if (r.includes("fisher") || r.includes("marine")) return t.roleFisher;
  return t.roleCitizen;
}
