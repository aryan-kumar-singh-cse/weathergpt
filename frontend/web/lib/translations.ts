/**
 * Translates any raw weather condition string into the selected vernacular language
 */
export function translateCondition(condition: string, lang: SupportedLanguage = "en"): string {
  if (!condition) return TRANSLATIONS[lang]?.clearSky || "Clear Sky";
  const lower = condition.toLowerCase();
  const t = TRANSLATIONS[lang] || TRANSLATIONS.en;

  if (lower.includes("thunder") || lower.includes("storm")) return t.thunderstorm;
  if (lower.includes("drizzle")) return t.lightDrizzle;
  if (lower.includes("rain") || lower.includes("shower")) return t.rain;
  if (lower.includes("snow") || lower.includes("ice") || lower.includes("frost")) return t.snow;
  if (lower.includes("fog") || lower.includes("mist") || lower.includes("haze")) return t.foggy;
  if (lower.includes("overcast")) return t.overcast;
  if (lower.includes("cloud") || lower.includes("partly")) return t.partlyCloudy;
  if (lower.includes("clear") || lower.includes("sun")) return t.clearSky;
  if (lower.includes("briefing") || lower.includes("overview")) return t.briefing;

  return condition;
}
